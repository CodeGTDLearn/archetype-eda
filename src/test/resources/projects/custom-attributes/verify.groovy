def _basedir = null
def _scriptdir = null
try { _basedir = basedir } catch (Throwable t) { _basedir = null }
try { _scriptdir = scriptdir } catch (Throwable t) { _scriptdir = null }

if (_basedir == null) {
    _basedir = System.getProperty('basedir')
}
if (_basedir == null) {
    throw new IllegalStateException("verify.groovy: basedir not bound")
}

def expectedEntityName = 'ContractEntity'
def expectedArtifactId = 'custom-attributes'
def packagePath = 'it/pkg/contractentity'
def expectedAttributes = [
    [name: 'id',        type: 'Long'],
    [name: 'name',      type: 'String'],
    [name: 'createdAt', type: 'String'],
    [name: 'statusPedido', type: 'StatusPedido'],
    [name: 'situacao',  type: 'Situacao'],
    [name: 'adminCredentials', type: 'AdminCredentials'],
]

def basedirFile = new File(_basedir as String)
def projectRoot = new File(basedirFile, "project/${expectedArtifactId}")
if (!projectRoot.exists()) {
    projectRoot = basedirFile
}

def candidatePaths = []
candidatePaths << new File(projectRoot, "src/main/java/${packagePath}/${expectedEntityName}.java")
candidatePaths << new File(projectRoot, "src/main/java/${packagePath}/entity/${expectedEntityName}.java")
candidatePaths << new File(projectRoot, "src/main/java/${packagePath}/model/${expectedEntityName}.java")
candidatePaths << new File(projectRoot, "src/main/java/${expectedEntityName}.java")
candidatePaths << new File(basedirFile, "src/main/java/${packagePath}/${expectedEntityName}.java")

def entityFile = candidatePaths.find { it.exists() }

if (entityFile == null) {
    throw new IllegalStateException(
        "verify.groovy: generated entity file not found. " +
        "Expected entity name: ${expectedEntityName}. " +
        "Tried paths: ${candidatePaths*.path.join(' | ')}"
    )
}

def entitySource = entityFile.text

expectedAttributes.each { attr ->
    def attrName = attr.name as String
    def attrType = attr.type as String
    def pattern = ~/private\s+${attrType}\s+${attrName}\s*[;=]/
    if (!(pattern.matcher(entitySource).find())) {
        throw new IllegalStateException(
            "verify.groovy: expected attribute '${attrName}' of type '${attrType}' " +
            "not found in generated entity ${entityFile.path}"
        )
    }
}

// ---------------------------------------------------------------------------
// FR-021 (PROJECT types): the referenced type is imported by the entity and
// the enums are generated by the post-processor in their own package.
// ---------------------------------------------------------------------------
if (!entitySource.contains('import it.pkg.domain.StatusPedido;')) {
    throw new IllegalStateException(
        "verify.groovy: the entity must import the referenced type 'it.pkg.domain.StatusPedido'. " +
        "Generated entity: ${entityFile.path}"
    )
}

if (!entitySource.contains('import it.pkg.contractentity.config.properties.credentials.AdminCredentials;')) {
    throw new IllegalStateException(
        "verify.groovy: the entity must import the referenced type " +
        "'it.pkg.contractentity.config.properties.credentials.AdminCredentials'. " +
        "Generated entity: ${entityFile.path}"
    )
}

// A type that belongs to the package of the entity does NOT need an import.
if (entitySource.contains('import it.pkg.contractentity.Situacao;')) {
    throw new IllegalStateException(
        "verify.groovy: the entity must NOT import 'it.pkg.contractentity.Situacao' " +
        "(same package as the entity). Generated entity: ${entityFile.path}"
    )
}

def enumFile = new File(projectRoot, "src/main/java/it/pkg/domain/StatusPedido.java")
if (!enumFile.isFile()) {
    throw new IllegalStateException(
        "verify.groovy: the enum 'StatusPedido' was not generated. Expected: ${enumFile.path}"
    )
}

def enumSource = enumFile.text
['ATIVO', 'CANCELADO'].each { constant ->
    if (!enumSource.contains(constant)) {
        throw new IllegalStateException(
            "verify.groovy: the enum 'StatusPedido' does not declare the constant '${constant}'. " +
            "Enum file: ${enumFile.path}"
        )
    }
}
if (!enumSource.contains('package it.pkg.domain;')) {
    throw new IllegalStateException(
        "verify.groovy: the enum 'StatusPedido' does not declare the package 'it.pkg.domain'. " +
        "Enum file: ${enumFile.path}"
    )
}

// An enum declared in the package of the entity is generated THERE.
def samePackageEnum = new File(projectRoot, "src/main/java/${packagePath}/Situacao.java")
if (!samePackageEnum.isFile()) {
    throw new IllegalStateException(
        "verify.groovy: the enum 'Situacao' was not generated in the package of the entity. " +
        "Expected: ${samePackageEnum.path}"
    )
}
if (!samePackageEnum.getText("UTF-8").contains('package it.pkg.contractentity;')) {
    throw new IllegalStateException(
        "verify.groovy: the enum 'Situacao' does not declare the package 'it.pkg.contractentity'. " +
        "Enum file: ${samePackageEnum.path}"
    )
}
if (!samePackageEnum.getText("UTF-8").contains('ABERTA')) {
    throw new IllegalStateException(
        "verify.groovy: the enum 'Situacao' does not declare the constant 'ABERTA'. " +
        "Enum file: ${samePackageEnum.path}"
    )
}

// The enum must NOT be duplicated in the package of the entity.
def duplicatedEnum = new File(projectRoot, "src/main/java/${packagePath}/StatusPedido.java")
if (duplicatedEnum.exists()) {
    throw new IllegalStateException(
        "verify.groovy: the enum 'StatusPedido' was duplicated in the entity package: ${duplicatedEnum.path}"
    )
}

// A REFERENCED class is never generated: only the enums are. The folder that
// holds the generated enums MUST carry the enum and nothing else.
def domainFolder = new File(projectRoot, "src/main/java/it/pkg/domain")
if (domainFolder.isDirectory()) {
    def domainFiles = domainFolder.listFiles().findAll { it.isFile() }.collect { it.name }.sort()
    if (domainFiles != ["StatusPedido.java"]) {
        throw new IllegalStateException(
            "verify.groovy: only the enum may be generated in 'it/pkg/domain'. " +
            "Found: ${domainFiles.join(', ')}"
        )
    }
}

// The referenced (existing) class keeps its own source: it is NOT turned into
// an enum and it is NOT overwritten.
def referencedClass = new File(projectRoot,
        "src/main/java/${packagePath}/config/properties/credentials/AdminCredentials.java")
if (!referencedClass.isFile()) {
    throw new IllegalStateException(
        "verify.groovy: the referenced class was not found in the generated project: ${referencedClass.path}"
    )
}
def referencedSource = referencedClass.getText("UTF-8")
if (referencedSource.contains('public enum AdminCredentials')) {
    throw new IllegalStateException(
        "verify.groovy: a referenced class MUST NOT be generated as an enum: ${referencedClass.path}"
    )
}
if (!referencedSource.contains('package it.pkg.contractentity.config.properties.credentials;')) {
    throw new IllegalStateException(
        "verify.groovy: the referenced class was overwritten: ${referencedClass.path}"
    )
}

// ---------------------------------------------------------------------------
// FR-021 (negative case): this profile keeps enable_folder_src_test_java=false,
// so the contracts folder MUST NOT exist in the generated project, even
// though entity_contract_path points to a real contract file.
// ---------------------------------------------------------------------------
def contractsFolder = new File(projectRoot, "src/test/resources/contracts")
if (contractsFolder.exists()) {
    throw new IllegalStateException(
        "verify.groovy: the contracts folder MUST NOT exist when " +
        "enable_folder_src_test_java=false, but it was found: ${contractsFolder.path}"
    )
}

return null
